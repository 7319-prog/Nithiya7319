/* =========================================================
   COMIC SYSTEM
========================================================= */

let currentPage = 0;

const comicBook = document.getElementById("comicBook");

const currentPageText =
    document.getElementById("currentPage");

const totalPagesText =
    document.getElementById("totalPages");

const previousBtn =
    document.getElementById("previousBtn");

const nextBtn =
    document.getElementById("nextBtn");

const homeBtn =
    document.getElementById("homeBtn");


totalPagesText.textContent = pages.length;



/* =========================================================
   DISPLAY PAGE
========================================================= */

function showPage(pageNumber) {

    if (pageNumber < 0) {
        pageNumber = 0;
    }

    if (pageNumber >= pages.length) {
        pageNumber = pages.length - 1;
    }

    currentPage = pageNumber;

    const page = pages[currentPage];

    comicBook.innerHTML = "";


    /* COVER */

    if (page.cover) {

        const cover = document.createElement("div");

        cover.className = "cover";

        cover.innerHTML = `

            <h1>${page.title}</h1>

            <h2>${page.subtitle}</h2>

            <p>
                ${page.description}
            </p>

            <p>
                <strong>CLICK NEXT TO BEGIN</strong>
            </p>

        `;

        comicBook.appendChild(cover);

    }


    /* NORMAL PAGE */

    else {

        const comicPage =
            document.createElement("div");

        comicPage.className = "comic-page";


        const title =
            document.createElement("div");

        title.className = "page-title";

        title.textContent = page.title;

        comicPage.appendChild(title);


        const panels =
            document.createElement("div");

        panels.className = "panels";


        page.panels.forEach(panel => {

            const panelElement =
                document.createElement("div");

            panelElement.className =
                `panel ${panel.scene}`;


            /* Character */

            if (panel.character) {
                const character =
    document.createElement("div");

character.className = "character";

const characterImages = {
    "NORA": "image/nora.jpg",
    "JENNIFER": "image/jennifer.jpg",
    "JAMIE": "image/jamie.jpg",
    "GEORGE": "image/george.jpg",
    "GIAN": "image/gian.jpg",
    "LUCAS": "image/lucas.jpg",
    "ZION": "image/zion.jpg"
};

if (characterImages[panel.character]) {

    const img = document.createElement("img");

    img.src = characterImages[panel.character];

    img.alt = panel.character;

    character.appendChild(img);

} else {

    character.textContent = panel.character;

}

panelElement.appendChild(character);

                

            }


            /* Speech */

            if (panel.speech) {

                const speech =
                    document.createElement("div");

                speech.className =
                    "speech";

                speech.textContent =
                    panel.speech;

                panelElement.appendChild(speech);

            }


            /* Caption */

            if (panel.caption) {

                const caption =
                    document.createElement("div");

                caption.className =
                    "caption";

                caption.textContent =
                    panel.caption;

                panelElement.appendChild(caption);

            }


            panels.appendChild(panelElement);

        });


        comicPage.appendChild(panels);

        comicBook.appendChild(comicPage);

    }


    /* PAGE NUMBER */

    currentPageText.textContent =
        currentPage + 1;


    /* BUTTONS */

    previousBtn.disabled =
        currentPage === 0;

    nextBtn.disabled =
        currentPage === pages.length - 1;


    window.scrollTo({
        top: 0,
        behavior: "smooth"
    });

}



/* =========================================================
   NEXT
========================================================= */

function nextPage() {

    if (currentPage < pages.length - 1) {

        showPage(currentPage + 1);

    }

}



/* =========================================================
   PREVIOUS
========================================================= */

function previousPage() {

    if (currentPage > 0) {

        showPage(currentPage - 1);

    }

}



/* =========================================================
   COVER
========================================================= */

function goHome() {

    showPage(0);

}



/* =========================================================
   BUTTON EVENTS
========================================================= */

nextBtn.addEventListener(
    "click",
    nextPage
);

previousBtn.addEventListener(
    "click",
    previousPage
);

homeBtn.addEventListener(
    "click",
    goHome
);



/* =========================================================
   KEYBOARD CONTROLS
========================================================= */

document.addEventListener(
    "keydown",
    function(event) {

        if (event.key === "ArrowRight") {

            nextPage();

        }

        if (event.key === "ArrowLeft") {

            previousPage();

        }

        if (event.key === "Home") {

            goHome();

        }

    }
);



/* =========================================================
   START
========================================================= */

showPage(0);